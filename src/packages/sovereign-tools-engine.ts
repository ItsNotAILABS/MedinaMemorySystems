export function getSovereignToolById(id: string): SovereignTool | undefined {
  return SOVEREIGN_TOOLS_REGISTRY.find(t => t.id === id);
}

export function getSovereignToolsByCategory(category: SovereignToolCategory): SovereignTool[] {
  return SOVEREIGN_TOOLS_REGISTRY.filter(t => t.category === category);
}

export function getAllSovereignToolExports() {
  return SOVEREIGN_TOOLS_REGISTRY.flatMap(t =>
    t.exports.map(exp => ({ ...exp, toolId: t.id, toolName: t.name }))
  );
}

export function searchSovereignTools(query: string): SovereignTool[] {
  const q = query.toLowerCase();
  return SOVEREIGN_TOOLS_REGISTRY.filter(t =>
    t.name.toLowerCase().includes(q) ||
    t.description.toLowerCase().includes(q) ||
    t.tagline.toLowerCase().includes(q) ||
    t.compatibleWith.some(c => c.toLowerCase().includes(q))
  );
}

